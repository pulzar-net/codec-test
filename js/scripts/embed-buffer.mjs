// The one copy of ChirpStack's Buffer lives with the Python package; the
// browser needs it as a string.
import { readFileSync, writeFileSync } from 'node:fs';

const source = readFileSync(new URL('../../src/codec_test/chirpstack_buffer.js', import.meta.url), 'utf8');
writeFileSync(
  new URL('../src/buffer.ts', import.meta.url),
  `// Generated by scripts/embed-buffer.mjs from src/codec_test/chirpstack_buffer.js.\n` +
    `export const BUFFER = ${JSON.stringify(source)};\n`,
);
